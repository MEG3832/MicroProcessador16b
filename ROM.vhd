      36 => B"0010_1110_0010_000_000", -- MOV A1, R2
      37 => B"0010_1110_0101_000_100", -- AND A1, R5
      38 => B"0100_000_0000_0000001",  -- BEQ 1
      39 => B"0011_0000000_0110001",  -- JUMP 49

      40 => B"0001_1110_0000000000",   -- LD A1, 0
      41 => B"0110_1110_0001_000000",  -- SW A1, R1

