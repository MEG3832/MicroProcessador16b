      25 => B"0110_1110_0001_000000",  -- SW A1, R1

      26 => B"0010_1110_0010_000_000", -- MOV A1, R2
      27 => B"0010_1110_0011_000_001", -- ADD A1, R3
      28 => B"0010_0010_1110_000_000", -- MOV R2, A1
      29 => B"0010_1110_0001_000_000", -- MOV A1, R1
      30 => B"0010_1110_0011_000_001", -- ADD A1, R3
